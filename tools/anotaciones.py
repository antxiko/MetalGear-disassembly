# --- los manejadores por tipo de actor ---
# Dos despachadores con el tipo - 1 en A (p00:575B y p01:7221 hacen `dec a`
# sobre (ix+0)): la creacion (p00:575F, tabla 0x5762) y cada cuadro
# (p01:722C, tabla 0x722F, desde el bucle p01:71E5). El banco de cada destino
# es el que midio el trazador (las lineas "entrada N de la tabla de 0x..." de
# src/pMM.entries). Un destino de varios tipos lleva todos en el nombre; los
# que ya tienen nombre arriba se quedan con el suyo.
TABLAS_POR_TIPO = (
    (0x5762, "crea_tipo", "la creacion del tipo"),
    (0x722F, "cuadro_tipo", "lo de cada cuadro del tipo"),
)


def _por_tipo():
    import glob
    import os
    import re
    raiz = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    destinos = {}
    for ruta in glob.glob(os.path.join(raiz, "src", "p[0-9][0-9].entries")):
        b = int(os.path.basename(ruta)[1:3])
        for ln in open(ruta, encoding="utf-8"):
            m = re.match(r"^0x([0-9A-Fa-f]+)\s+#\s+p\d\d:[0-9A-Fa-f]{4} entrada (\d+) de la tabla de 0x([0-9A-Fa-f]{4})", ln)
            if m:
                tabla = int(m.group(3), 16)
                for t, pref, que in TABLAS_POR_TIPO:
                    if t == tabla:
                        destinos.setdefault((b, int(m.group(1), 16), pref, que), []).append(int(m.group(2)) + 1)
    fuera = {}
    for (b, d, pref, que), tipos in destinos.items():
        tipos = sorted(set(tipos))
        nombre = "%s%s_%s" % (pref, "s" if len(tipos) > 1 else "", "_".join("%d" % t for t in tipos))
        fuera[(b, d)] = (nombre, "%s%s %s" % (que, "s" if len(tipos) > 1 else "", ", ".join("%d" % t for t in tipos)))
    return fuera


