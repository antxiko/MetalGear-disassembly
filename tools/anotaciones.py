# Que banco se ve en cada ventana. Konami4 en trios (tools/paginas.py): el
# banco b de codigo corre con su trio; el banco 0 (0x4000) no tiene trio fijo.
def trio(b):
    if b == 0:
        return {}
    t = 3 * ((b - 1) // 3) + 1
    return {0x6000: t, 0x8000: t + 1, 0xA000: t + 2}


