# --- los trampolines del banco 0 (p00:4050-4195) ---
# Cada uno es `call X` y una cadena de `jr` que acaba en p00:4198: bancos 1-2-3
# y el banco de zona (0xF0F6) otra vez en 0xA000. Los usa el codigo de los
# bancos de zona (6, 9, 12, 15, que corren en 0xA000 con el 1 y el 2 debajo)
# para llamar a rutinas que cambian de banco y volver con el suyo puesto. Se
# nombran por la rutina a la que llaman; el banco de X sale de lo que midio
# el trazador (src/pMM.entries).
TRAMPOLINES = (0x4050, 0x4198)


def _trampolines():
    import glob
    import os
    import re
    raiz = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    medido = {}
    for ruta in glob.glob(os.path.join(raiz, "src", "p[0-9][0-9].entries")):
        mm = int(os.path.basename(ruta)[1:3])
        for ln in open(ruta, encoding="utf-8"):
            m = re.match(r"^0x([0-9A-Fa-f]+)\s+#\s+p00:([0-9A-Fa-f]{4}) call", ln)
            if m:
                medido[int(m.group(2), 16)] = (mm, int(m.group(1), 16))
    listado = glob.glob(os.path.join(raiz, "src", "*_p00.asm"))
    if not listado:
        return {}
    fuera, etiqueta = {}, None
    por_nombre = {v[0]: k for k, v in RUTINAS.items()}
    for ln in open(listado[0], encoding="utf-8"):
        m = re.match(r"^([A-Za-z_][A-Za-z_0-9]*):", ln)
        if m:
            etiqueta = m.group(1)
            continue
        m = re.match(r"^\tcall ([A-Za-z_0-9]+)\s*;([0-9a-f]{4})", ln)
        if not m or etiqueta is None:
            etiqueta = None
            continue
        a = int(m.group(2), 16)
        etiqueta = None
        if not TRAMPOLINES[0] <= a < TRAMPOLINES[1]:
            continue
        x = m.group(1)
        if x in por_nombre:
            destino = por_nombre[x]
        elif a in medido:
            destino = medido[a]
        else:
            mm = re.match(r"^(?:L_([0-9A-F]{4})|0([0-9a-f]{4})h)$", x)
            destino = (0, int(mm.group(1) or mm.group(2), 16)) if mm else None
        if destino in RUTINAS:
            nom, que = RUTINAS[destino]
            fuera[(0, a)] = (nom + "_y_vuelve", "llama a %s (p%02d:%04X) y deja otra vez los bancos 1-2 y el de zona" % (nom, destino[0], destino[1]))
    return fuera


for _k, _v in _trampolines().items():
    RUTINAS.setdefault(_k, _v)
